#!/usr/bin/env python3
"""Build rootfs/etc/roots.der: Mozilla's trusted roots as concatenated DER.

    python3 -I lib/x509/tools/mkroots.py [cacert.pem]

Without an argument it downloads https://curl.se/ca/cacert.pem (curl's
extraction of the certificates Mozilla trusts for TLS server
authentication from NSS certdata.txt). Each PEM block becomes its DER
bytes; DER is self-delimiting, so the output is just their concatenation
(X509TrustStore(concatenatedDER:) in lib/x509 reads it). A README next to
it records the source date and the license (MPL 2.0).
Standard library only.
"""
import base64, hashlib, os, re, sys, urllib.request

URL = "https://curl.se/ca/cacert.pem"
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", ".."))
OUT = os.path.join(ROOT, "rootfs", "etc", "roots.der")
README = os.path.join(ROOT, "rootfs", "etc", "roots.README")

def main():
    if len(sys.argv) > 1:
        with open(sys.argv[1], "rb") as f:
            pem = f.read().decode("ascii", "replace")
        source = os.path.basename(sys.argv[1])
    else:
        with urllib.request.urlopen(URL, timeout=30) as r:
            pem = r.read().decode("ascii", "replace")
        source = URL
    m = re.search(r"Certificate data from Mozilla as of: (.*)", pem)
    asof = m.group(1).strip() if m else "unknown date"
    blocks = re.findall(r"-----BEGIN CERTIFICATE-----(.*?)-----END CERTIFICATE-----", pem, re.S)
    ders = []
    for b in blocks:
        der = base64.b64decode("".join(b.split()))
        if der[0] != 0x30:
            sys.exit("not a DER SEQUENCE")
        ders.append(der)
    data = b"".join(ders)
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "wb") as f:
        f.write(data)
    with open(README, "w") as f:
        f.write(f"""roots.der: trusted root certificates for TLS (lib/x509 X509TrustStore)

{len(ders)} DER certificates, concatenated (each is a self-delimiting DER
SEQUENCE). Generated by lib/x509/tools/mkroots.py from {source}
(Mozilla certificate data as of {asof}).
SHA-256 of roots.der: {hashlib.sha256(data).hexdigest()}

The certificates come from Mozilla's NSS root store (certdata.txt), as
extracted by the curl project (https://curl.se/docs/caextract.html). That
data is licensed under the Mozilla Public License 2.0
(https://mozilla.org/MPL/2.0/).
""")
    print(f"{len(ders)} certificates, {len(data)} bytes -> {os.path.relpath(OUT, ROOT)}")

main()
