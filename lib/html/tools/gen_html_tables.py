FOREIGN_ATTRS = ["xlink:actuate", "xlink:arcrole", "xlink:href", "xlink:role", "xlink:show",
                 "xlink:title", "xlink:type", "xml:lang", "xml:space", "xmlns:xlink"]

def gen_names():
    w = open(os.path.join(out, "HTMLNames.swift"), "w")
    w.write("// GENERATED by tools/gen_html_tables.py. Do not edit.\n\n")
    w.write("/// Known HTML element names (the ones the tree builder treats specially).\n")
    w.write("enum HTMLTag: UInt8 {\n    case unknown\n")
    for t in TAGS:
        w.write("    case %s\n" % t)
    w.write("""
    static func lookup(_ s: String) -> HTMLTag {
        switch s {
""")
    for t in TAGS:
        w.write('        case "%s": return .%s\n' % (t, t))
    w.write("        default: return .unknown\n        }\n    }\n}\n\n")
    def sw(fn, pairs, doc):
        w.write("/// %s\n" % doc)
        w.write("func %s(_ s: String) -> String? {\n    switch s {\n" % fn)
        for a, b in pairs:
            w.write('    case "%s": return "%s"\n' % (a, b))
        w.write("    default: return nil\n    }\n}\n\n")
    sw("htmlSVGTagName", [(t.lower(), t) for t in SVG_TAGS], "Lowercase SVG tag name to its camelCase form.")
    sw("htmlSVGAttrName", [(t.lower(), t) for t in SVG_ATTRS], "Lowercase SVG attribute name to its camelCase form.")
    w.write("/// Attributes whose names the parser splits into prefix and local name.\n")
    w.write("func htmlIsForeignAdjustedAttr(_ s: String) -> Bool {\n    switch s {\n    case %s: return true\n    default: return false\n    }\n}\n"
            % ", ".join('"%s"' % a for a in FOREIGN_ATTRS))
    w.close()

gen_entities(sys.argv[1] if len(sys.argv) > 1 else os.path.join(here, "entities.json"))
gen_names()
