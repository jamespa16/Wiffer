#!/usr/bin/env python3
"""Generate lib/html/HTMLEntities.swift and lib/html/HTMLNames.swift.

    python3 -I lib/html/tools/gen_html_tables.py [entities.json]

entities.json is https://html.spec.whatwg.org/entities.json (a copy is kept
next to this script). The entity table is emitted as two ASCII string
literals (StaticString, so no heap and no big array literal to compile):

  htmlEntityRecords  records sorted by name (bytes), each record being
                       1 char   len+0x30
                       name     the name without '&', including the ';' if
                                the key has one (legacy names exist both
                                with and without ';')
                       4 chars  base64 of  cp1 | secondIndex << 17
  htmlEntityOffsets  3 base64 chars (18 bits) per record: its offset into
                     htmlEntityRecords, so lookup is a binary search.

secondIndex 0 means a single code point, otherwise it indexes
htmlEntitySeconds (the few second code points that exist).
"""
import json, os, sys

here = os.path.dirname(os.path.abspath(__file__))
out = os.path.join(here, "..")
B64 = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/"

def b64(v, n):
    return "".join(B64[(v >> (6 * i)) & 63] for i in reversed(range(n)))

def gen_entities(path):
    d = json.load(open(path))
    names = sorted(k[1:] for k in d)  # byte order == str order for ASCII
    seconds = sorted({v["codepoints"][1] for v in d.values() if len(v["codepoints"]) == 2})
    assert len(seconds) < 16
    recs, offs, pos = [], [], 0
    for n in names:
        cps = d["&" + n]["codepoints"]
        assert cps[0] < (1 << 17) and 2 <= len(n) <= 32
        val = cps[0] | ((seconds.index(cps[1]) + 1) << 17 if len(cps) == 2 else 0)
        r = chr(0x30 + len(n)) + n + b64(val, 4)
        offs.append(pos)
        pos += len(r)
        recs.append(r)
    assert pos < (1 << 18)
    w = open(os.path.join(out, "HTMLEntities.swift"), "w")
    w.write("// GENERATED by tools/gen_html_tables.py from the WHATWG entities.json.\n")
    w.write("// Do not edit. %d named character references.\n\n" % len(names))
    w.write("let htmlEntityCount = %d\n" % len(names))
    w.write("let htmlEntitySeconds: [UInt32] = [0, %s]\n\n" % ", ".join(str(s) for s in seconds))
    for label, items in (("htmlEntityRecords", recs), ("htmlEntityOffsets", [b64(o, 3) for o in offs])):
        w.write("let %s: StaticString = \"\"\"\n" % label)
        s = "".join(items)
        for i in range(0, len(s), 100):
            last = i + 100 >= len(s)
            w.write(s[i:i + 100] + ("\n" if last else "\\\n"))
        w.write("\"\"\"\n\n")
    w.close()

# ---------------------------------------------------------------- names
