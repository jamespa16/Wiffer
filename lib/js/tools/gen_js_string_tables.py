#!/usr/bin/env python3
"""Generate lib/js/jsstringtables.swift: the String built-ins' Unicode data.

    python3 -I lib/js/tools/gen_js_string_tables.py

All data comes from Python's unicodedata / str case mapping (Unicode 17),
which implement the unconditional full case mappings of SpecialCasing.txt
and the normalization data of UnicodeData.txt / CompositionExclusions.

Tables are StaticStrings of fixed-width base64 records (big-endian, 6 bits
per char), looked up by binary search with no heap and no array literal:

  jsCaseLower   cp:4 to:4              single-code-point lower mappings
  jsCaseUpper   cp:4 to:4              single-code-point upper mappings
  jsCaseUpperMulti cp:4 n:1 c1:4 c2:4 c3:4   full upper mappings (n = 2 or 3)
  jsCasedRanges / jsCaseIgnorableRanges    range:7 = first | last << 21
                                       (for the Final_Sigma condition)
  jsNormCCC     lo:4 hi:4 ccc:2        canonical combining classes != 0
  jsNormNFD     cp:4 off:4 len:1       full canonical decomposition, offset
  jsNormNFDPool cp:4 ...               into this pool of code points
  jsNormNFKD    cp:4 off:4 len:1       full compatibility decomposition, only
  jsNormNFKDPool cp:4 ...              where it differs from the NFD one
  jsNormComp    c1:4 c2:4 c:4          primary composites, sorted by (c1, c2)

Hangul syllables are algorithmic and not in the tables. U+0130's lower
mapping (i + U+0307) is the only multi-unit lower mapping (asserted); Final
Sigma is handled by the code.
"""
import os, sys, unicodedata

here = os.path.dirname(os.path.abspath(__file__))
out = os.path.join(here, "..", "jsstringtables.swift")
B64 = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/"
MAX = 0x110000
HANGUL = range(0xAC00, 0xD7A4)


def b64(v, n):
    assert 0 <= v < (1 << (6 * n)), (v, n)
    return "".join(B64[(v >> (6 * i)) & 63] for i in reversed(range(n)))


def emit(w, name, recs, comment):
    """recs: list of strings (already encoded records)."""
    s = "".join(recs)
    w.write("// %s\n" % comment)
    w.write("let %sCount = %d\n" % (name, len(recs)))
    w.write("let %s: StaticString = \"\"\"\n" % name)
    if not s:
        w.write("\"\"\"\n\n")
        return
    for i in range(0, len(s), 98):
        last = i + 98 >= len(s)
        w.write(s[i:i + 98] + ("\n" if last else "\\\n"))
    w.write("\"\"\"\n\n")


def ranges(cps):
    out_ = []
    for cp in sorted(cps):
        if out_ and out_[-1][1] == cp - 1:
            out_[-1][1] = cp
        else:
            out_.append([cp, cp])
    return out_


def main():
    lower, upper, upper_multi = [], [], []
    cased, ignorable = set(), set()
    mid = {0x27, 0x2E, 0x3A, 0xB7, 0x387, 0x55F, 0x5F4, 0x2018, 0x2019, 0x2024, 0x2027,
           0xFE13, 0xFE52, 0xFE55, 0xFF07, 0xFF0E, 0xFF1A}
    for cp in range(MAX):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        ch = chr(cp)
        lo, up = ch.lower(), ch.upper()
        if lo != ch:
            if len(lo) == 1:
                lower.append((cp, ord(lo)))
            else:
                assert cp == 0x130 and lo == "i̇", hex(cp)
        if up != ch:
            if len(up) == 1:
                upper.append((cp, ord(up)))
            else:
                assert len(up) in (2, 3)
                upper_multi.append((cp, [ord(c) for c in up]))
        cat = unicodedata.category(ch)
        if ch.islower() or ch.isupper() or cat == "Lt":
            cased.add(cp)
        if cat in ("Mn", "Me", "Cf", "Lm", "Sk") or cp in mid:
            ignorable.add(cp)

    ccc_runs = []
    for cp in range(MAX):
        c = unicodedata.combining(chr(cp)) if not 0xD800 <= cp <= 0xDFFF else 0
        if c:
            if ccc_runs and ccc_runs[-1][1] == cp - 1 and ccc_runs[-1][2] == c:
                ccc_runs[-1][1] = cp
            else:
                ccc_runs.append([cp, cp, c])

    nfd, nfkd = [], []
    for cp in range(MAX):
        if 0xD800 <= cp <= 0xDFFF or cp in HANGUL:
            continue
        ch = chr(cp)
        d = unicodedata.normalize("NFD", ch)
        k = unicodedata.normalize("NFKD", ch)
        if d != ch:
            nfd.append((cp, [ord(c) for c in d]))
        if k != d:
            nfkd.append((cp, [ord(c) for c in k]))

    comp = []
    for cp in range(MAX):
        if 0xD800 <= cp <= 0xDFFF or cp in HANGUL:
            continue
        ch = chr(cp)
        dec = unicodedata.decomposition(ch)
        if not dec or dec.startswith("<"):
            continue
        parts = dec.split()
        if len(parts) != 2:
            continue
        if unicodedata.normalize("NFC", ch) != ch:
            continue  # composition exclusion
        comp.append((int(parts[0], 16), int(parts[1], 16), cp))
    comp.sort()

    w = open(out, "w")
    w.write("// GENERATED by tools/gen_js_string_tables.py from Python unicodedata %s. Do not edit.\n"
            % unicodedata.unidata_version)
    w.write("// Case mapping and normalization data for the String built-ins; the record\n")
    w.write("// layouts are described in the script.\n\n")
    emit(w, "jsCaseLower", [b64(a, 4) + b64(b, 4) for a, b in lower], "single-code-point lower mappings")
    emit(w, "jsCaseUpper", [b64(a, 4) + b64(b, 4) for a, b in upper], "single-code-point upper mappings")
    emit(w, "jsCaseUpperMulti",
         [b64(a, 4) + b64(len(m), 1) + "".join(b64(x, 4) for x in (m + [0, 0])[:3]) for a, m in upper_multi],
         "full upper mappings of two or three code points")
    emit(w, "jsCasedRanges", [b64(a | (b << 21), 7) for a, b in ranges(cased)], "Cased")
    emit(w, "jsCaseIgnorableRanges", [b64(a | (b << 21), 7) for a, b in ranges(ignorable)], "Case_Ignorable")
    emit(w, "jsNormCCC", [b64(a, 4) + b64(b, 4) + b64(c, 2) for a, b, c in ccc_runs], "combining classes")
    for name, lst, what in (("jsNormNFD", nfd, "canonical"), ("jsNormNFKD", nfkd, "compatibility")):
        pool, recs = [], []
        for cp, m in lst:
            recs.append(b64(cp, 4) + b64(len(pool), 4) + b64(len(m), 1))
            pool.extend(m)
        emit(w, name, recs, "full %s decompositions (offset, length into the pool)" % what)
        emit(w, name + "Pool", [b64(x, 4) for x in pool], "pool for " + name)
    emit(w, "jsNormComp", [b64(a, 4) + b64(b, 4) + b64(c, 4) for a, b, c in comp], "primary composites")
    w.close()
    print("lower %d upper %d multi %d cased %d ign %d ccc %d nfd %d nfkd %d comp %d" % (
        len(lower), len(upper), len(upper_multi), len(ranges(cased)), len(ranges(ignorable)),
        len(ccc_runs), len(nfd), len(nfkd), len(comp)))


main()
