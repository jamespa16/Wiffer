#!/usr/bin/env python3
# Generates lib/js/tests/jscore_vectors.swift: number conversion vectors for
# jscore_tests.swift, from Python's correctly rounded float parsing, its
# shortest repr, and exact Decimal arithmetic (deterministic seed).
#   python3 lib/js/tools/jsnumbervectors.py > lib/js/tests/jscore_vectors.swift
import random, struct
from decimal import Decimal, ROUND_HALF_UP, Context

random.seed(9)

def bits(x): return struct.unpack('<Q', struct.pack('<d', x))[0]
def frombits(b): return struct.unpack('<d', struct.pack('<Q', b))[0]

def shortest(x):
    # digits string and exponent n (ES: value = 0.digits * 10^n)
    d = Decimal(repr(x))
    sign, digs, exp = d.as_tuple()
    s = ''.join(map(str, digs)).rstrip('0') or '0'
    k = len(s)
    n = len(digs) + exp
    return s, n

def js_tostring(x):
    if x != x: return 'NaN'
    if x == 0: return '0'
    if x < 0: return '-' + js_tostring(-x)
    if x == float('inf'): return 'Infinity'
    s, n = shortest(x)
    k = len(s)
    if k <= n <= 21: return s + '0' * (n - k)
    if 0 < n <= 21: return s[:n] + '.' + s[n:]
    if -6 < n <= 0: return '0.' + '0' * (-n) + s
    e = n - 1
    es = ('+' if e >= 0 else '-') + str(abs(e))
    return s[0] + ('.' + s[1:] if k > 1 else '') + 'e' + es

def js_tofixed(x, f):
    if abs(x) >= 1e21: return js_tostring(x)
    d = Decimal(x).quantize(Decimal(1).scaleb(-f), rounding=ROUND_HALF_UP, context=Context(prec=2000))
    s = format(d.copy_abs(), 'f')
    return ('-' if x < 0 else '') + s

def round_sig(x, p):
    # digits (length p) and exponent e for |x| rounded half up to p digits
    c = Context(prec=p, rounding=ROUND_HALF_UP)
    d = c.plus(Decimal(abs(x)))
    sign, digs, exp = d.as_tuple()
    digs = list(digs) + [0] * (p - len(digs))
    e = len(d.as_tuple().digits) + exp - 1
    return ''.join(map(str, digs[:p])), e

def js_toexp(x, f):
    s, e = round_sig(x, f + 1)
    m = s[0] + ('.' + s[1:] if f > 0 else '')
    return ('-' if x < 0 else '') + m + 'e' + ('+' if e >= 0 else '-') + str(abs(e))

def js_toprec(x, p):
    s, e = round_sig(x, p)
    sg = '-' if x < 0 else ''
    if e < -6 or e >= p:
        return sg + s[0] + ('.' + s[1:] if p > 1 else '') + 'e' + ('+' if e >= 0 else '-') + str(abs(e))
    if e == p - 1: return sg + s
    if e >= 0: return sg + s[:e + 1] + '.' + s[e + 1:]
    return sg + '0.' + '0' * (-(e + 1)) + s

def rand_double():
    r = random.random()
    if r < 0.4:
        while True:
            x = frombits(random.getrandbits(64))
            if x == x and x not in (float('inf'), float('-inf')): return x
    if r < 0.6: return random.uniform(-1000, 1000)
    if r < 0.75: return float(random.randint(-10**17, 10**17)) / 10 ** random.randint(0, 20)
    if r < 0.85: return frombits(random.getrandbits(52))  # subnormals
    return random.choice([1, -1]) * random.randint(1, 9) * 10.0 ** random.randint(-325, 308)

out = []
out.append('// Generated by lib/js/tools/jsnumbervectors.py; do not edit.')
out.append('')
out.append('/// (bits, Number::toString)')
out.append('let jsVecToString: [(UInt64, String)] = [')
for _ in range(500):
    x = rand_double()
    out.append('    (0x%016x, "%s"),' % (bits(x), js_tostring(x)))
out.append(']')
out.append('')
out.append('/// (decimal string, bits of the correctly rounded double)')
out.append('let jsVecStrtod: [(String, UInt64)] = [')
def rand_decimal():
    r = random.random()
    if r < 0.3:
        nd = random.randint(1, 25)
        s = ''.join(random.choice('0123456789') for _ in range(nd))
        return s + 'e' + str(random.randint(-340, 320))
    if r < 0.5:
        # halfway between two doubles, exactly
        x = abs(rand_double())
        if x == 0 or x == float('inf') or x >= 1.7e308: x = 1.5
        y = frombits(bits(x) + 1)
        h = Context(prec=2000).divide(Context(prec=2000).add(Decimal(x), Decimal(y)), 2)
        return format(h, 'e') if random.random() < 0.5 else str(h)
    if r < 0.6:
        x = abs(rand_double())
        C = Context(prec=2000); h = C.add(Decimal(x), C.divide(C.subtract(Decimal(frombits(bits(x) + 1)), Decimal(x)), 2))
        delta = Decimal(10) ** (h.adjusted() - 60)
        return format(C.add(h, delta if random.random() < .5 else -delta), "e")
    if r < 0.8:
        return repr(rand_double()).lstrip('-')
    nd = random.randint(20, 900)
    s = ''.join(random.choice('0123456789') for _ in range(nd))
    p = random.randint(0, nd)
    return s[:p] + '.' + s[p:] + ('e' + str(random.randint(-400, 300)) if random.random() < 0.5 else '')
for _ in range(500):
    s = rand_decimal()
    out.append('    ("%s", 0x%016x),' % (s, bits(float(s))))
out.append(']')
out.append('')
out.append('/// (bits, f, p, toFixed(f), toExponential(f), toPrecision(p))')
out.append('let jsVecFormat: [(UInt64, Int, Int, String, String, String)] = [')
for _ in range(300):
    r = random.random()
    if r < 0.5: x = random.uniform(-1e6, 1e6)
    elif r < 0.8: x = float(random.randint(-10**6, 10**6)) / 10 ** random.randint(1, 8)
    else: x = abs(rand_double()) * random.choice([1, -1])
    if x == 0: x = 0.5
    f = random.randint(0, 25)
    p = random.randint(1, 25)
    out.append('    (0x%016x, %d, %d, "%s", "%s", "%s"),' % (bits(x), f, p, js_tofixed(x, f), js_toexp(x, f), js_toprec(x, p)))
out.append(']')
print('\n'.join(out))
