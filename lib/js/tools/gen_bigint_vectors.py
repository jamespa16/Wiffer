#!/usr/bin/env python3
"""Generate lib/js/tests/jsbuiltins4_bigvectors.swift: BigInt reference vectors
computed with Python's integers. Usage: lib/js/tools/gen_bigint_vectors.py"""
import random, os
random.seed(262)

def rnd(maxbits):
    k = random.random()
    if k < 0.1: return random.choice([0, 1, -1, 2, -2, 2**32, 2**32 - 1, -2**32, 2**64, 2**64 - 1, 2**31, -2**63, 2**63 - 1])
    bits = random.randint(1, maxbits)
    if k < 0.2:
        v = 2 ** bits + random.choice([-1, 0, 1])
    elif k < 0.25:
        v = 2 ** bits - 1
    else:
        v = random.getrandbits(bits)
    return -v if random.random() < 0.5 else v

lines = []
def add(*a): lines.append(" ".join(str(x) for x in a))

def tdiv(a, b):
    q = abs(a) // abs(b)
    return q if (a < 0) == (b < 0) else -q
def trem(a, b): return a - b * tdiv(a, b)

for i in range(260):
    mb = 3200 if i % 13 == 0 else 200 if i % 3 else 70
    a, b = rnd(mb), rnd(mb)
    add("+", a, b, a + b)
    add("-", a, b, a - b)
    add("*", a, b, a * b)
    if b != 0:
        add("/", a, b, tdiv(a, b))
        add("%", a, b, trem(a, b))
    add("&", a, b, a & b)
    add("|", a, b, a | b)
    add("^", a, b, a ^ b)
    s = random.randint(0, 130)
    add("<<", a, s, a << s)
    add(">>", a, s, a >> s)
    add("<<", a, -s, a >> s)
    add(">>", a, -s, a << s)
    add("~", a, 0, ~a)
    add("neg", a, 0, -a)
    r = random.choice([2, 3, 7, 8, 10, 16, 32, 36])
    def tostr(n, r):
        if n == 0: return "0"
        d = "0123456789abcdefghijklmnopqrstuvwxyz"; s = ""; m = abs(n)
        while m: s = d[m % r] + s; m //= r
        return ("-" if n < 0 else "") + s
    add("str", a, r, tostr(a, r))
    bits = random.choice([0, 1, 3, 8, 31, 32, 33, 63, 64, 65, 100, 200])
    add("asU", a, bits, a % (1 << bits) if bits else 0)
    sg = a % (1 << bits) if bits else 0
    if bits and sg >= 1 << (bits - 1): sg -= 1 << bits
    add("asI", a, bits, sg)
    try: f = repr(float(a))
    except OverflowError: f = "Infinity" if a > 0 else "-Infinity"
    add("num", a, 0, f)
for i in range(40):
    a = rnd(60); e = random.randint(0, 40)
    add("**", a, e, a ** e)
# Doubles near ties: BigInt -> Number rounding
for i in range(60):
    a = random.getrandbits(random.randint(54, 90)) | 1
    a = (a >> 3 << 3) + random.choice([0, 1, 4, 3, 5, 2**random.randint(1, 5)])
    add("num", a, 0, repr(float(a)))
# Division with Knuth D corner cases
for i in range(60):
    b = random.getrandbits(64) | (1 << 63)
    q = random.getrandbits(random.randint(32, 200))
    r = random.randrange(b)
    a = q * b + r
    add("/", a, b, q); add("%", a, b, r)
    b2 = (1 << (32 * random.randint(2, 5))) - random.choice([1, 2**31, 2**32 - 1])
    add("/", a, b2, a // b2); add("%", a, b2, a % b2)

out = os.path.join(os.path.dirname(__file__), "..", "tests", "jsbuiltins4_bigvectors.swift")
with open(out, "w") as f:
    f.write("// Generated by lib/js/tools/gen_bigint_vectors.py: BigInt reference vectors from\n// Python integers (op a b result per line). Do not edit.\n")
    f.write('let jsBigIntVectors = #"""\n' + "\n".join(lines) + '\n"""#\n')
print(len(lines), "vectors")
