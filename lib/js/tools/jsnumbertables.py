print("// Each 128-bit entry is two UInt64s, low word first.")
print("")
print(pairs("jsRyuPow5Split", ryu_pow5, "/// Ryu: 5^i normalized to 125 bits (truncated), i in 0..<326."))
print("")
print(pairs("jsRyuPow5InvSplit", ryu_inv, "/// Ryu: floor(2^(bitlen(5^i) - 1 + 125) / 5^i) + 1, i in 0..<342."))
print("")
print(pairs("jsLemirePow5", lem, "/// Eisel-Lemire: 128-bit approximations of 5^q, q in -342...308 (fast_float's table)."))
