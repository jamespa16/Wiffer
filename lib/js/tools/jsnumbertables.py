# Generates lib/js/jsnumbertables.swift: Ryu (d2s) and Eisel-Lemire power tables.
M64 = (1 << 64) - 1
def pairs(name, vals, doc):
    out = [doc, "let %s: [UInt64] = [" % name]
    for v in vals:
        out.append("    0x%016x, 0x%016x," % (v & M64, v >> 64))
    out.append("]")
    return "\n".join(out)

ryu_pow5 = []
for i in range(326):
    p = 5 ** i
    j = p.bit_length() - 125
    ryu_pow5.append(p >> j if j >= 0 else p << -j)
ryu_inv = []
for i in range(342):
    p = 5 ** i
    j = p.bit_length() - 1 + 125
    ryu_inv.append((1 << j) // p + 1)
lem = []
for q in range(-342, 0):
    p5 = 5 ** -q
    z = 0
    while (1 << z) < p5: z += 1
    if q >= -27:
        b = z + 127
        c = 2 ** b // p5 + 1
    else:
        b = 2 * z + 2 * 64
        c = 2 ** b // p5 + 1
        while c >= (1 << 128): c //= 2
    lem.append(c)
for q in range(0, 309):
    p5 = 5 ** q
    while p5 < (1 << 127): p5 *= 2
    while p5 >= (1 << 128): p5 //= 2
    lem.append(p5)

