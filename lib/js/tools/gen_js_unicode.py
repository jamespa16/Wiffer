#!/usr/bin/env python3
"""Generate lib/js/jsunicode.swift: the ID_Start / ID_Continue tables.

    python3 -I lib/js/tools/gen_js_unicode.py [DerivedCoreProperties.txt]

With a DerivedCoreProperties.txt (https://www.unicode.org/Public/<ver>/ucd/)
the properties are read from it. Without one they are derived from Python's
unicodedata with the UAX #31 definitions:

  ID_Start    = L* + Nl + Other_ID_Start - Pattern_Syntax - Pattern_White_Space
  ID_Continue = ID_Start + Mn + Mc + Nd + Pc + Other_ID_Continue - Pattern_*

(the two agree for Unicode 17; the script checks when given the file).

Each table is a StaticString of fixed-width records, 7 base64 chars per
range (first | last << 21), sorted, so a lookup is a binary search with no
heap and no big array literal to compile. jsContinueOnly holds the ranges
of ID_Continue that are not ID_Start, so IdentifierPart is
isStart || inContinueOnly. ASCII never reaches the tables (the lexer has
its own fast path).
"""
import os, sys, unicodedata

here = os.path.dirname(os.path.abspath(__file__))
out = os.path.join(here, "..", "jsunicode.swift")
B64 = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/"

OTHER_ID_START = [0x1885, 0x1886, 0x2118, 0x212E, 0x309B, 0x309C]
OTHER_ID_CONTINUE = [0x00B7, 0x0387] + list(range(0x1369, 0x1372)) + [0x19DA, 0x200C, 0x200D, 0x30FB, 0xFF65]
# Pattern_Syntax code points that are otherwise letters (the only one).
PATTERN_LETTERS = [0x2E2F]


def derived():
    start, cont = set(), set()
    for cp in range(0x80, 0x110000):
        c = unicodedata.category(chr(cp))
        if c in ("Lu", "Ll", "Lt", "Lm", "Lo", "Nl"):
            start.add(cp)
        elif c in ("Mn", "Mc", "Nd", "Pc"):
            cont.add(cp)
    start |= set(OTHER_ID_START)
    start -= set(PATTERN_LETTERS)
    cont |= set(OTHER_ID_CONTINUE)
    cont |= start
    return start, cont


def from_file(path):
    props = {"ID_Start": set(), "ID_Continue": set()}
    for line in open(path, encoding="utf-8"):
        line = line.split("#")[0].strip()
        if not line:
            continue
        rng, prop = [x.strip() for x in line.split(";")[:2]]
        if prop not in props:
            continue
        a, _, b = rng.partition("..")
        lo, hi = int(a, 16), int(b or a, 16)
        props[prop].update(range(max(lo, 0x80), hi + 1))
    return props["ID_Start"], props["ID_Continue"]


def ranges(s):
    out, cps = [], sorted(s)
    for cp in cps:
        if out and out[-1][1] == cp - 1:
            out[-1][1] = cp
        else:
            out.append([cp, cp])
    return out


def b64(v, n):
    return "".join(B64[(v >> (6 * i)) & 63] for i in reversed(range(n)))


def emit(w, name, rs):
    s = "".join(b64(a | (b << 21), 7) for a, b in rs)
    w.write("let %sCount = %d\n" % (name, len(rs)))
    w.write("let %s: StaticString = \"\"\"\n" % name)
    for i in range(0, len(s), 98):
        last = i + 98 >= len(s)
        w.write(s[i:i + 98] + ("\n" if last else "\\\n"))
    w.write("\"\"\"\n\n")


def main():
    if len(sys.argv) > 1:
        start, cont = from_file(sys.argv[1])
        ds, dc = derived()
        if (ds, dc) != (start, cont):
            print("note: unicodedata %s differs from %s (%d/%d start, %d/%d continue)"
                  % (unicodedata.unidata_version, sys.argv[1], len(ds ^ start), len(start),
                     len(dc ^ cont), len(cont)))
        source = os.path.basename(sys.argv[1])
    else:
        start, cont = derived()
        source = "Python unicodedata %s" % unicodedata.unidata_version
    rs, rc = ranges(start), ranges(cont - start)
    w = open(out, "w")
    w.write("// GENERATED by tools/gen_js_unicode.py from %s. Do not edit.\n" % source)
    w.write("// ID_Start: %d code points in %d ranges; ID_Continue-only: %d in %d.\n"
            % (len(start), len(rs), len(cont - start), len(rc)))
    w.write("// Records are 7 base64 chars: first | last << 21 (see the script).\n\n")
    emit(w, "jsIDStartTable", rs)
    emit(w, "jsIDContinueOnlyTable", rc)
    w.close()


main()
