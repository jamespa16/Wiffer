// The RegExp engine (ROADMAP Phase 9C, "RegExp"): ECMAScript 2022 patterns
// (with Annex B syntax outside unicode mode), compiled to a small bytecode
// and run by a backtracking matcher with an explicit backtrack stack. It
// is VM-independent: patterns and subjects are UTF-16 code units, results
// are capture indices. The JS-visible RegExp object, lastIndex handling,
// Symbol.replace and friends are built on top of this by the built-ins.
//
// Files: jsregexp.swift (this API), jsregexp_parse.swift (pattern parser
// and every early error), jsregexp_compile.swift (character sets, Unicode
// properties, case folding, bytecode), jsregexp_match.swift (the matcher),
// jsregexptables.swift (generated by tools/gen_js_regexp_tables.py).
//
// API contract:
//
//   jsRegExpValidate(pattern:flags:) -> String?
//       nil when the literal is valid, else the SyntaxError message. The
//       parser calls it for every regex literal (early errors).
//
//   jsRegExpCompile(pattern:flags:) throws(JSRegExpError) -> JSRegExpProgram
//       Compile once and keep the program: it is immutable apart from a
//       reusable scratch area, so one program may be shared by every
//       RegExp object with the same source and flags (JSRegExpCache does
//       that for literals evaluated in a loop and `new RegExp(s)` with a
//       repeated s). Not thread-safe (one realm runs on one thread).
//       A `v` flag is accepted and treated as `u` (ES2024 class set syntax
//       is not implemented yet).
//
//   program.exec(subject, from: lastIndex, stepLimit:) -> JSRegExpResult
//       subject: any random-access collection of UInt8 (Latin-1) or UInt16
//       units indexed from 0 (Array, UnsafeBufferPointer; JSHeap's
//       `regExpExec` passes a string cell's storage without copying).
//       Matching starts at `from` (clamped at 0; past the end there is no
//       match). Sticky (`y`) programs try only there; others scan forward
//       (by code point in unicode mode). In unicode mode a start inside a
//       surrogate pair moves back to the pair. `g` and `d` don't change
//       matching: lastIndex updates and the indices array are the
//       built-ins' job.
//         .match(m)       m.start(i) / m.end(i) for i in 0...captureCount,
//                         -1/-1 for an unmatched group; m.captures holds
//                         them as [start0, end0, start1, end1, ...].
//         .noMatch
//         .stepLimit      more than stepLimit steps (instructions plus
//                         backtracks; default JSLimits.maxRegexSteps): the
//                         VM must turn this into an uncatchable termination
//                         with JSTerminationReason.regexSteps (ReDoS).
//         .stackLimit     the backtrack stack passed
//                         program.maxBacktrackEntries (default 4M entries,
//                         48 MiB): the VM throws a catchable RangeError
//                         (other engines do the same).
//
//   program.captureCount           groups, not counting group 0
//   program.groupNames[i]          name of group i (1-based; [] if unnamed;
//                                  index 0 is unused)
//   program.namedGroups            (name, index) in group order, for the
//                                  `groups` object
//   program.flags / program.source the flags and pattern as given
//
// Steps: every bytecode instruction, every character a simple greedy loop
// consumes and every backtrack counts one step. Skipping ahead to a
// literal first character between attempts is free.

/// The RegExp flags, as parsed from a flags string.
public struct JSRegExpFlags: Equatable {
    public var bits: UInt8

    public static let hasIndices: UInt8 = 1   // d
    public static let global: UInt8 = 2       // g
    public static let ignoreCase: UInt8 = 4   // i
    public static let multiline: UInt8 = 8    // m
    public static let dotAll: UInt8 = 16      // s
    public static let unicode: UInt8 = 32     // u
    public static let unicodeSets: UInt8 = 64 // v
    public static let sticky: UInt8 = 128     // y

    public init(bits: UInt8 = 0) { self.bits = bits }

    /// Parse a flags string: nil for an unknown or repeated flag, or u+v.
    public init?<C: Collection>(units: C) where C.Element == UInt16 {
        var b: UInt8 = 0
        for u in units {
            let bit: UInt8
            switch u {
            case 0x64: bit = JSRegExpFlags.hasIndices
            case 0x67: bit = JSRegExpFlags.global
            case 0x69: bit = JSRegExpFlags.ignoreCase
            case 0x6D: bit = JSRegExpFlags.multiline
            case 0x73: bit = JSRegExpFlags.dotAll
            case 0x75: bit = JSRegExpFlags.unicode
            case 0x76: bit = JSRegExpFlags.unicodeSets
            case 0x79: bit = JSRegExpFlags.sticky
            default: return nil
            }
            if b & bit != 0 { return nil }
            b |= bit
        }
        if b & (JSRegExpFlags.unicode | JSRegExpFlags.unicodeSets) == JSRegExpFlags.unicode | JSRegExpFlags.unicodeSets {
            return nil
        }
        bits = b
    }

    @inline(__always) public func has(_ bit: UInt8) -> Bool { bits & bit != 0 }
    public var hasIndices: Bool { has(JSRegExpFlags.hasIndices) }
    public var global: Bool { has(JSRegExpFlags.global) }
    public var ignoreCase: Bool { has(JSRegExpFlags.ignoreCase) }
    public var multiline: Bool { has(JSRegExpFlags.multiline) }
    public var dotAll: Bool { has(JSRegExpFlags.dotAll) }
    public var unicode: Bool { has(JSRegExpFlags.unicode) }
    public var unicodeSets: Bool { has(JSRegExpFlags.unicodeSets) }
    public var sticky: Bool { has(JSRegExpFlags.sticky) }
    /// Unicode mode: `u` or `v` (code points, strict syntax, \p, folding).
    public var unicodeMode: Bool { bits & (JSRegExpFlags.unicode | JSRegExpFlags.unicodeSets) != 0 }

    /// The flags in the canonical order of RegExp.prototype.flags ("dgimsuvy").
    public var string: String {
        var s: [UInt8] = []
        let letters: [UInt8] = [0x64, 0x67, 0x69, 0x6D, 0x73, 0x75, 0x76, 0x79]
        for k in 0..<8 where bits & (1 << UInt8(k)) != 0 { s.append(letters[k]) }
        return String(decoding: s, as: UTF8.self)
    }
}

/// A pattern SyntaxError (the message only; the VM adds "Invalid regular
/// expression: /src/flags: ").
public struct JSRegExpError: Error {
    public var message: String
    public init(_ message: String) { self.message = message }
}

/// Capture positions of a successful match, in code units.
public struct JSRegExpMatch {
    /// [start0, end0, start1, end1, ...]; -1 for groups that didn't match.
    public var captures: [Int32]

    public var count: Int { captures.count / 2 }
    public func start(_ i: Int) -> Int { i >= 0 && 2 * i < captures.count ? Int(captures[2 * i]) : -1 }
    public func end(_ i: Int) -> Int { i >= 0 && 2 * i + 1 < captures.count ? Int(captures[2 * i + 1]) : -1 }
    public func matched(_ i: Int) -> Bool { start(i) >= 0 && end(i) >= 0 }
}

public enum JSRegExpResult {
    case match(JSRegExpMatch)
    case noMatch
    /// The step budget ran out: terminate the script (JSTerminationReason.regexSteps).
    case stepLimit
    /// The backtrack stack cap was hit: throw a RangeError.
    case stackLimit
}

/// Is this pattern/flags pair a valid regular expression? nil if so, else
/// the SyntaxError message. Used for regex literals at parse time.
public func jsRegExpValidate<P: Collection, F: Collection>(pattern: P, flags: F) -> String?
    where P.Element == UInt16, F.Element == UInt16 {
    guard let f = JSRegExpFlags(units: flags) else { return "invalid regular expression flags" }
    do {
        _ = try jsReParse(Array(pattern), f)
        return nil
    } catch {
        return error.message
    }
}

/// Compile a pattern. Throws the SyntaxError message for an invalid one.
public func jsRegExpCompile<P: Collection, F: Collection>(pattern: P, flags: F) throws(JSRegExpError) -> JSRegExpProgram
    where P.Element == UInt16, F.Element == UInt16 {
    guard let f = JSRegExpFlags(units: flags) else { throw JSRegExpError("invalid regular expression flags") }
    return try jsRegExpCompile(pattern: pattern, flags: f)
}

public func jsRegExpCompile<P: Collection>(pattern: P, flags f: JSRegExpFlags) throws(JSRegExpError) -> JSRegExpProgram
    where P.Element == UInt16 {
    let src = Array(pattern)
    let ast = try jsReParse(src, f)
    var c = JSReCompiler(ast: ast, flags: f)
    try c.compile()
    return JSRegExpProgram(source: src, flags: f, ast: ast, compiler: c)
}

/// A compiled regular expression. See the contract at the top of the file.
public final class JSRegExpProgram {
    public let source: [UInt16]
    public let flags: JSRegExpFlags
    public let captureCount: Int
    /// groupNames[i] is the name of group i ([] if it has none); [0] unused.
    public let groupNames: [[UInt16]]
    /// Named groups in group-number order.
    public let namedGroups: [(name: [UInt16], index: Int)]
    /// Backtrack stack cap, in entries (12 bytes each).
    public var maxBacktrackEntries = 4 << 20

    let code: [Int32]
    let sets: [UInt32]
    let regCount: Int
    let caseRuns: [UInt64]         // decoded canonicalize table (ignoreCase only)
    let firstChar: Int32           // literal first code unit to scan for, or -1
    let anchoredStart: Bool        // begins with ^ outside multiline mode
    var scratchRegs: [Int32] = []
    var scratchStack: [Int32] = []

    init(source: [UInt16], flags: JSRegExpFlags, ast: JSReAST, compiler c: JSReCompiler) {
        self.source = source
        self.flags = flags
        captureCount = ast.captureCount
        var names: [[UInt16]] = [[]]
        var named: [(name: [UInt16], index: Int)] = []
        for (i, n) in ast.groupNames.enumerated() {
            names.append(n)
            if !n.isEmpty { named.append((name: n, index: i + 1)) }
        }
        groupNames = names
        namedGroups = named
        code = c.code
        sets = c.sets
        regCount = c.regCount
        caseRuns = c.caseRuns
        firstChar = c.firstChar
        anchoredStart = c.anchoredStart
    }

    /// Run the program on a subject (see the contract at the top).
    public func exec<S: RandomAccessCollection>(_ subject: S, from lastIndex: Int, stepLimit: Int = JSLimits().maxRegexSteps) -> JSRegExpResult
        where S.Element: FixedWidthInteger & UnsignedInteger, S.Index == Int {
        var m = JSReMatcher(program: self, subject: subject, stepLimit: stepLimit)
        let r = m.run(from: lastIndex)
        m.giveBackScratch()
        return r
    }

    /// Bytecode listing, for tests and debugging.
    public func disassemble() -> String { jsReDisassemble(code) }
}

/// A small cache of compiled programs keyed by source and flags, so a
/// regex literal evaluated in a loop, or `new RegExp(s)` with the same s,
/// compiles once. Least recently used programs are dropped past `capacity`.
public final class JSRegExpCache {
    public var capacity: Int
    var entries: [JSRegExpProgram] = []

    public init(capacity: Int = 64) { self.capacity = capacity }

    public func program<P: Collection>(pattern: P, flags: JSRegExpFlags) throws(JSRegExpError) -> JSRegExpProgram
        where P.Element == UInt16 {
        let src = Array(pattern)
        for i in 0..<entries.count where entries[i].flags == flags && entries[i].source == src {
            let p = entries[i]
            if i != entries.count - 1 { entries.remove(at: i); entries.append(p) }
            return p
        }
        let p = try jsRegExpCompile(pattern: src, flags: flags)
        entries.append(p)
        if entries.count > max(capacity, 1) { entries.removeFirst() }
        return p
    }

    public func removeAll() { entries.removeAll() }
}

extension JSHeap {
    /// Run a program on a heap string without copying it. Uses
    /// limits.maxRegexSteps; .stepLimit means terminate with .regexSteps.
    public func regExpExec(_ p: JSRegExpProgram, _ s: JSValue, from lastIndex: Int) -> JSRegExpResult {
        let steps = limits.maxRegexSteps
        guard let i = stringCell(s) else {
            let empty: [UInt8] = []
            return p.exec(empty, from: lastIndex, stepLimit: steps)
        }
        if strings[i].isWide {
            let units = strings[i].utf16
            return units.withUnsafeBufferPointer { p.exec($0, from: lastIndex, stepLimit: steps) }
        }
        let bytes = strings[i].latin1
        return bytes.withUnsafeBufferPointer { p.exec($0, from: lastIndex, stepLimit: steps) }
    }
}
